#!/usr/bin/env python3
"""Reference pre-tokenization of code points added in Unicode 17 (and the ones around them).

Writes tests/text/pretokenizer_unicode_cases.inc, read by tests/text/test_tokenizer.cpp: the
pieces that Hugging Face tokenizers (pinned: 0.23.3) cuts the Qwen3 and gpt-oss split regexes
into, which text::Pattern must reproduce. See tools/text/generate_onig_unicode_tables.py.

    pip install tokenizers==0.23.3
    python tools/text/pretokenizer_unicode_cases.py tests/text/pretokenizer_unicode_cases.inc
"""

import sys

from tokenizers import Regex
from tokenizers.pre_tokenizers import Split

QWEN = r"(?i:'s|'t|'re|'ve|'m|'ll|'d)|[^\r\n\p{L}\p{N}]?\p{L}+|\p{N}| ?[^\s\p{L}\p{N}]+[\r\n]*|\s*[\r\n]+|\s+(?!\S)|\s+"
OSS = r"[^\r\n\p{L}\p{N}]?[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]*[\p{Ll}\p{Lm}\p{Lo}\p{M}]+(?i:'s|'t|'re|'ve|'m|'ll|'d)?|[^\r\n\p{L}\p{N}]?[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]+[\p{Ll}\p{Lm}\p{Lo}\p{M}]*(?i:'s|'t|'re|'ve|'m|'ll|'d)?|\p{N}{1,3}| ?[^\s\p{L}\p{N}]+[\r\n/]*|\s*[\r\n]+|\s+(?!\S)|\s+"
cps = [0x295, 0x88F, 0xC5C, 0xCDC, 0xA7CE, 0xA7D2, 0x1ACF, 0x10ED0, 0x16EA0, 0x323AF, 0x323B0,
       0x33479, 0x3347A, 0x1FAEF]


def cpp(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if 32 <= b < 127 and c not in '"\\':
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


rows = []
for name, rx in (("kQwen3", QWEN), ("kGptOss", OSS)):
    pt = Split(Regex(rx), "isolated")
    for c in cps:
        x = chr(c)
        for t in (x + "'s", "a" + x + "'s", x + "_", "x_" + x, " " + x + "b", x + "1", "A" + x + "B'S"):
            pcs = [p for p, _ in pt.pre_tokenize_str(t)]
            rows.append((name, t, pcs))
with open(sys.argv[1], "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/text/pretokenizer_unicode_cases.py with tokenizers 0.23.3.\n")
    for name, t, pcs in rows:
        f.write("    {%s, %s, {%s}},\n" % (name, cpp(t), ", ".join(cpp(p) for p in pcs)))
