#!/usr/bin/env python3
"""Fail on a hand-written board identity: a board's facts written as a literal.

A board is named by its PCI id and read from the registry (core/board_registry.h, generated from
core/data/gpu_facts.json): `board_registry::board(0x2B85)`. A literal that spells a board's compute
capability, SMs, L2 and bandwidth is a second copy of the registry row, the class of bug behind
#502, #507, #556 and #594 (roadmap #612, step 9).

The text of every tracked C++ file is read as one token stream (comments and the inside of string
and character literals blanked, line breaks kept as white space), so a literal may span lines, sit
in a macro or follow any declarator. Flagged:

  1. `Board` (or a `using`/`typedef` alias of it) initialised with `{...}` or `(...)` that has at
     least two arguments and whose first is a constant (digits, `kName` constants, parentheses,
     operators, or a designated `.major = 12`); any declarator between the type and the bracket
     (`Board k[] = {`, `const Board& b = {`, `Board const b(`);
  2. a `.board = {...}` designated initialiser with a constant first argument;
  3. any brace tuple of five numbers that reads as a board (major 5..15, minor 0..9, SMs 1..400,
     L2 up to 512 MiB, bandwidth of 100 GB/s or more), optionally a bool after it:
     `{12, 0, 170, 96, 1792}`, `{7, 5, 68, 5.5, 616, true}`, wherever it stands (`return {...}`,
     a call argument, `b = {...}`, `std::array<Board, 2>{{...}}`, a table row). Lists of sizes,
     token ids and shapes fall outside the ranges.

Not flagged: conversions from fields (`Board{cc / 10, cc % 10, sms}`, `Board{row->major, ...}`),
`struct Board {` and other declarations, a same-named type of another namespace (`chess::Board`),
words that only start with Board (`BoardRow`, `BoardCount`). Known limits: a board literal whose
first field is not a constant and not five numbers (a mix of names) is not seen; an alias declared
in another file is not known; code under `#if 0` is read like any other.

Exceptions are files named in ALLOW with the exact number of flagged lines and a reason: a new
literal in an allowed file, or a removed one, fails until the number is reviewed.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUFFIXES = {".h", ".hh", ".hpp", ".hxx", ".inc", ".ipp", ".tpp",
            ".c", ".cc", ".cpp", ".cxx", ".cu", ".cuh"}
SKIP_DIRS = {"third_party", ".git", "build"}

# path -> (flagged lines, reason). Every entry is a reviewed exception, pinned by count.
ALLOW = {
    "src/core/measured_boards.h":
        (12, "pins: static_asserts that each registry row equals the literal it replaced"),
    "src/ops/generic/r8_decode_table.h":
        (9, "generated by tools/bench/r8_decode_table.py, which still writes each table's board as "
            "numbers (one row has drifted from the registry); to emit registry ids (#612 step 9)"),
    "tests/test_device.cpp":
        (6, "boards written by hand next to the registry rows they approximate, plus hypothetical "
            "ones (cc 13.0, synthetic SM counts) probing board_distance; to move to the registry"),
    "tests/test_gate_atlas.cpp":
        (4, "hypothetical boards with a quantity zeroed or altered, probing the lookup rules"),
    "tests/test_context_cost.cpp":
        (2, "real boards written by hand as fixtures of the context-cost resolver; to move to the "
            "registry"),
}

NUM = r"[-+]?(?:0[xX][0-9a-fA-F']+|\d[\d']*(?:\.\d*)?(?:[eE][-+]?\d+)?|\.\d+)[fFuUlL]*"
TUPLE = re.compile(r"\{\s*(%s)\s*,\s*(%s)\s*,\s*(%s)\s*,\s*(%s)\s*,\s*(%s)\s*(?:,\s*(?:true|false)\s*)?\}"
                   % ((NUM,) * 5))
DOT_BOARD = re.compile(r"\.board\s*=\s*\{")
ALIAS = re.compile(r"\busing\s+(\w+)\s*=\s*(?:::)?(?:ninferno\s*::\s*)?Board\s*;"
                   r"|\btypedef\s+(?:ninferno\s*::\s*)?Board\s+(\w+)\s*;")
NUMTOK = re.compile(
    r"0[xX][0-9a-fA-F']+[uUlL]*|\d[\d']*(?:\.\d*)?(?:[eE][-+]?\d+)?[fFuUlL]*|\.\d+[fF]?")
RAW = re.compile(r'R"([^()\\ ]{0,16})\(')


def blank(text):
    """`text` with comments and the inside of string/char literals replaced by spaces; line breaks
    stay, so offsets and line numbers are unchanged."""
    out, i, n = [], 0, len(text)

    def fill(a, b):
        out.append("".join(c if c == "\n" else " " for c in text[a:b]))

    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = i
            while j < n and text[j] != "\n":
                j = j + 2 if text[j] == "\\" and j + 1 < n else j + 1
            fill(i, j)
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            fill(i, j)
            i = j
        elif c == '"':
            m = RAW.match(text, i - 1) if i and text[i - 1] == "R" else None
            if m:
                end = text.find(")" + m.group(1) + '"', m.end())
                j = n if end < 0 else end + len(m.group(1)) + 2
                out.append('"')
                fill(i + 1, max(i + 1, j - 1))
                out.append('"')
                i = j
                continue
            j = i + 1
            while j < n and text[j] != '"' and text[j] != "\n":
                j = j + 2 if text[j] == "\\" and j + 1 < n else j + 1
            out.append('"')
            fill(i + 1, j)
            if j < n and text[j] == '"':
                out.append('"')
                j += 1
            i = j
        elif c == "'" and not (i and (text[i - 1].isalnum() or text[i - 1] == "_")):
            j = i + 1
            while j < n and text[j] != "'" and text[j] != "\n":
                j = j + 2 if text[j] == "\\" and j + 1 < n else j + 1
            out.append("'")
            fill(i + 1, j)
            if j < n and text[j] == "'":
                out.append("'")
                j += 1
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def group(code, i):
    """The text between the bracket at code[i] and its match, or None when unbalanced."""
    depth = 0
    for j in range(i, len(code)):
        if code[j] in "({[":
            depth += 1
        elif code[j] in ")}]":
            depth -= 1
            if depth == 0:
                return code[i + 1:j]
    return None


def args(body):
    """Top-level comma separated parts of `body`."""
    parts, depth, cur = [], 0, []
    for c in body:
        if c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    parts.append("".join(cur))
    return [p.strip() for p in parts if p.strip()]


def constant(arg):
    """True when `arg` is made of numbers, `kName` constants, parentheses and operators only."""
    arg = re.sub(r"^\.\w+\s*=\s*", "", arg)
    arg = re.sub(r"\bk[A-Z]\w*\b", "0", arg)
    arg = NUMTOK.sub("0", arg)
    return bool(arg.strip()) and re.fullmatch(r"[\s0()+\-*/%<>|&~^]*", arg) is not None


def number(tok):
    tok = tok.replace("'", "").rstrip("fFuUlL") if not tok.lower().startswith("0x") else tok.replace("'", "")
    return float(int(tok, 16)) if tok.lower().startswith(("0x", "-0x", "+0x")) else float(tok)


def board_shaped(m):
    """The five numbers of a tuple read as (major, minor, SMs, L2 MiB, GB/s) of a board: a major
    5..15, a minor 0..9, SMs 1..400, an L2 of at most 512, a bandwidth of 100 or more. Lists of
    sizes, token ids and shapes fall outside."""
    try:
        major, minor, sms, l2, bw = (number(g) for g in m.groups())
    except ValueError:
        return False
    return (5 <= major <= 15 and major == int(major) and 0 <= minor <= 9 and minor == int(minor)
            and 1 <= sms <= 400 and sms == int(sms) and 0 <= l2 <= 512 and bw >= 100)


def starts_board_literal(body):
    a = args(body)
    return len(a) >= 2 and constant(a[0])


def violations(text):
    """[(line number, source line)] of the board literals in `text`, one entry per line."""
    code = blank(text)
    names = {"Board"}
    for m in ALIAS.finditer(code):
        names.add(m.group(1) or m.group(2))
    typed = re.compile(
        r"(?<![\w:.])(?:ninferno\s*::\s*)?(?:%s)\b(?!\s*::)\s*(?:const\b\s*)?[&*]*\s*(?:const\b\s*)?"
        r"(?:\w+\s*)?(?:\[[^\]]*\]\s*)?=?\s*([{(])" % "|".join(map(re.escape, sorted(names))))
    starts = []
    for m in typed.finditer(code):
        body = group(code, m.end() - 1)
        if body is not None and starts_board_literal(body):
            starts.append(m.start())
    for m in DOT_BOARD.finditer(code):
        body = group(code, m.end() - 1)
        if body is not None and starts_board_literal(body):
            starts.append(m.start())
    for m in TUPLE.finditer(code):
        if board_shaped(m):
            starts.append(m.start())
    lines = text.splitlines()
    found = {}
    for s in starts:
        n = code.count("\n", 0, s) + 1
        found.setdefault(n, lines[n - 1].strip() if n <= len(lines) else "")
    return sorted(found.items())


def files(root):
    """C++ sources to scan: the tracked files outside third_party, whatever the directory (apps/,
    bench/ and include/ too); without a git checkout, a walk of the same."""
    paths = None
    if (root / ".git").exists():
        r = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True)
        if r.returncode == 0:
            paths = [root / p for p in r.stdout.decode("utf-8", "replace").split("\0") if p]
    if paths is None:
        paths = [p for p in root.rglob("*") if not SKIP_DIRS & set(p.relative_to(root).parts)]
    return sorted(p for p in paths
                  if p.suffix in SUFFIXES and p.is_file()
                  and "third_party" not in p.relative_to(root).parts)


def scan(root, allow=ALLOW):
    """[(path, line, text)] of the flagged lines outside `allow`, plus an entry (line 0) per
    allowed file whose number of flagged lines differs from its pin."""
    bad, seen = [], {}
    for p in files(root):
        rel = p.relative_to(root).as_posix()
        hits = violations(p.read_text(encoding="utf-8", errors="replace"))
        if rel in allow:
            seen[rel] = len(hits)
            continue
        bad.extend((rel, n, line) for n, line in hits)
    for rel, (count, _reason) in sorted(allow.items()):
        got = seen.get(rel, 0)
        if got != count:
            bad.append((rel, 0, f"allow-list pins {count} flagged line(s), the file has {got}"))
    return bad


def main():
    bad = scan(ROOT)
    for rel, n, line in bad:
        print(f"{rel}:{n}: board literal outside the registry: {line}" if n
              else f"{rel}: {line}")
    if bad:
        print("Name the board by PCI id: board_registry::board(0x....) (core/board_registry.h).")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
